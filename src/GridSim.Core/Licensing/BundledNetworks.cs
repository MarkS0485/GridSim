using System.Collections.Concurrent;
using System.Security.Cryptography;

namespace GridSim.Core.Licensing;

/// <summary>
/// The one list of Bundled Networks (LICENSE.md section 1): network models shipped with the Software that never
/// count toward a tier's bus limit. The CLI (<c>Gated</c>), the WPF shell and the Web case catalogue all ask this
/// class, so the three front-ends cannot disagree about the same shipped case.
///
/// R002 (October 2026 review): the CLI kept its own list, which lacked <c>data/gb-full</c>, so on the free tier
/// every CLI verb refused the shipped 3,539-bus GB case with exit 2 while the Web and WPF apps loaded it.
///
/// What is bundled: the committed MATPOWER test library (IEEE / CIGRE / PEGASE cases under <c>data/matpower</c>),
/// the UK boundary data (<c>data/uk</c>) and the shipped GB cases (<c>data/gb-synthetic</c>, <c>data/gb-reduced</c>,
/// <c>data/gb-full</c>). Anything else, including a materialised <c>gda-*</c> model or a <c>gda-out/</c> tree, is a
/// licensed user network. Built-in cases (<c>case9</c> and friends) never touch a file loader and are exempt by
/// construction.
///
/// <para><b>N216 (October 2026): anchored to the shipped data root.</b> A path is bundled only when it sits under one
/// of <see cref="DataRoots"/>: the install's own <c>data/</c> folder (next to the running program, where every
/// front-end's project file copies the shipped cases), plus, for a program run from a GridSim source checkout's build
/// output, that checkout's <c>data/</c> folder. Before, ANY path with a <c>data/&lt;bundled folder&gt;</c> segment
/// counted, wherever it sat (<c>C:\anything\data\uk\mycase.m</c>), so a user network escaped the tier's bus limit just by
/// being copied under a folder of the right name. The shipped GB reduced model lives in <c>data/uk</c> (the case name
/// <c>gb-reduced</c> is an alias of <c>uk</c>); the folder list used to name a <c>data/gb-reduced</c> folder that does
/// not exist, and no longer does.</para>
///
/// <para><b>N229 (October 2026, LF5; ruled: adopt with the F-release work): bundled by CONTENT, not location.</b> N216's
/// anchoring left one way round the tier limit: anyone who can write into the install's own <c>data/</c> folder (an
/// administrator on a Program Files install, anyone on a portable unzip) could drop a large user network there, or edit a
/// shipped case into one, and it counted as bundled. Now a path is bundled only when it is in place (the N216 rule) AND
/// its content is what shipped: every data root carries a manifest, <see cref="ManifestFileName"/>, listing the
/// line-ending-normalised SHA-256 (<see cref="ContentHash"/>) of every file under the <see cref="DataFolders"/>
/// (generated by <c>tools/gen_bundled_manifest.py</c> from the source data, checked against it by a test, and copied
/// next to the program with the data by every front end's project file). A FILE is bundled when the manifest lists
/// its path under the root and its hash matches. A FOLDER (a JSON case folder, a whole data folder) is bundled when it
/// holds at least one file and EVERY file in it, at any depth, is listed with a matching hash: a file added to a
/// shipped folder or a shipped file edited makes the folder a user network. A root with no manifest (or a manifest that
/// cannot be read) has nothing bundled under it: the licence check then runs, which is the safe direction. Line ends are
/// normalised (CR LF read as LF) before hashing because a git checkout on Windows writes text files with CR LF and one on
/// Linux with LF; the shipped bytes are otherwise compared exactly. Hashes are cached per file by its size and last
/// write time, so a case loaded again costs a dictionary lookup. The explicit-roots overload
/// <see cref="IsBundledPath(string?, IReadOnlyList{string})"/> keeps the location rule alone (its contract and tests are
/// about the anchoring).</para>
/// </summary>
public static class BundledNetworks
{
    /// <summary>The folders directly under a shipped <c>data/</c> root whose contents are Bundled Networks. N216: the
    /// stale <c>gb-reduced</c> entry is gone (no such folder ships; the <c>gb-reduced</c> case id loads <c>data/uk</c>).</summary>
    public static IReadOnlyList<string> DataFolders { get; } =
        ["matpower", "uk", "gb-synthetic", "gb-full", "intl", "dist3ph"];   // Q7 / Q29: shipped starter maps and feeders

    /// <summary>
    /// N216: the shipped data roots, resolved once. Always the install's <c>data/</c> folder
    /// (<see cref="AppContext.BaseDirectory"/> + <c>data</c>). When the program runs from a build output inside a GridSim
    /// source checkout (its folder is below <c>&lt;checkout&gt;/src/</c>, <c>&lt;checkout&gt;/tests/</c> or
    /// <c>&lt;checkout&gt;/tools/</c> (the checkout's own tools, UiSmoke and AssetSmoke among them), and the
    /// checkout root holds <c>GridSim.slnx</c> and a <c>data/</c> folder), that checkout's <c>data/</c> folder too: it
    /// is the source the shipped copy is made from, and developers and the test suite load cases from it. An installed
    /// program (no checkout above it) has exactly one root.
    /// </summary>
    public static IReadOnlyList<string> DataRoots { get; } = ResolveDataRoots(AppContext.BaseDirectory);

    /// <summary>
    /// The data roots for a program whose folder is <paramref name="baseDirectory"/> (see <see cref="DataRoots"/>).
    /// Public so the rule can be tested against any layout.
    /// </summary>
    public static IReadOnlyList<string> ResolveDataRoots(string baseDirectory)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(baseDirectory);
        string install = Path.GetFullPath(Path.Combine(baseDirectory, "data"));
        var roots = new List<string> { install };
        // Walk up for the source checkout: the nearest folder holding GridSim.slnx. The program must sit below that
        // checkout's src/, tests/ or tools/ folder (a build output), not merely somewhere beneath a folder that happens
        // to hold a file of that name. tools/ (2026-10-24): the checkout's own tools build there and load its cases in
        // the same way; without it UiSmoke on the free tier refused the bundled gb-full (3,539 buses) its checklist uses.
        var dir = new DirectoryInfo(Path.GetFullPath(baseDirectory));
        for (DirectoryInfo? d = dir; d is not null; d = d.Parent)
        {
            if (!File.Exists(Path.Combine(d.FullName, "GridSim.slnx"))) continue;
            string checkoutData = Path.Combine(d.FullName, "data");
            bool underBuildTree = IsUnder(dir.FullName, Path.Combine(d.FullName, "src"))
                || IsUnder(dir.FullName, Path.Combine(d.FullName, "tests"))
                || IsUnder(dir.FullName, Path.Combine(d.FullName, "tools"));
            if (underBuildTree && Directory.Exists(checkoutData) && !SamePath(checkoutData, install))
                roots.Add(Path.GetFullPath(checkoutData));
            break;   // the nearest checkout only
        }
        return roots;
    }

    /// <summary>The JSON case ids (Web catalogue ids, CLI named cases) that are Bundled Networks.</summary>
    public static IReadOnlyList<string> JsonCaseIds { get; } = ["gb-synthetic", "gb-reduced", "gb-full"];

    /// <summary>True when <paramref name="caseId"/> names a bundled JSON case (exact, case-sensitive id).</summary>
    public static bool IsBundledJsonCase(string? caseId) => caseId is not null && JsonCaseIds.Contains(caseId);

    /// <summary>
    /// True when a file or directory path points at a Bundled Network: after resolving it to a full path (so
    /// <c>..</c> segments cannot climb out), it is one of the <see cref="DataFolders"/> directly under one of the
    /// shipped <see cref="DataRoots"/>, or anything inside one. The match is on whole segments, so
    /// <c>data/gb-fullish</c> or <c>data/ukx</c> are NOT bundled. N216: a <c>data/&lt;folder&gt;</c> segment anywhere
    /// else (a user's copy under <c>C:\work\data\uk\</c>) is NOT bundled: the tier limit applies to it. Case is ignored
    /// on Windows and macOS (case-insensitive file systems) and respected elsewhere; either separator is accepted. A
    /// path that cannot be resolved is not bundled, so the licence check still runs on it.
    /// </summary>
    /// <remarks>N229: and its content is what shipped (the class summary: the root's <see cref="ManifestFileName"/> lists
    /// the file, or every file of the folder, with a matching <see cref="ContentHash"/>).</remarks>
    public static bool IsBundledPath(string? path) => IsBundledByContent(path, DataRoots);

    /// <summary>
    /// N229: the full rule of <see cref="IsBundledPath(string?)"/> (location AND content) against explicit
    /// <paramref name="dataRoots"/>, each read with its own <see cref="ManifestFileName"/> (tests build a root of their
    /// own rather than writing into a real install). A root's manifest is read once per process.
    /// </summary>
    public static bool IsBundledByContent(string? path, IReadOnlyList<string> dataRoots)
    {
        ArgumentNullException.ThrowIfNull(dataRoots);
        return Locate(path, dataRoots) is (string full, string root) && ContentIsShipped(full, root);
    }

    /// <summary>The LOCATION rule of <see cref="IsBundledPath(string?)"/> (N216) against explicit
    /// <paramref name="dataRoots"/> (tests). It does not read the manifest: the content check (N229) belongs to the
    /// one-argument form, against the real data roots.</summary>
    public static bool IsBundledPath(string? path, IReadOnlyList<string> dataRoots)
    {
        ArgumentNullException.ThrowIfNull(dataRoots);
        return Locate(path, dataRoots) is not null;
    }

    /// <summary>N216: the full path of <paramref name="path"/> and the full path of the data root it sits in (in one of
    /// the <see cref="DataFolders"/>), or null when it is in none (or cannot be resolved).</summary>
    private static (string Full, string Root)? Locate(string? path, IReadOnlyList<string> dataRoots)
    {
        if (string.IsNullOrWhiteSpace(path)) return null;
        string full;
        try { full = Path.GetFullPath(path); }
        catch (Exception e) when (e is ArgumentException or NotSupportedException or PathTooLongException) { return null; }

        foreach (string root in dataRoots)
        {
            if (string.IsNullOrWhiteSpace(root)) continue;
            string rootFull;
            try { rootFull = Path.GetFullPath(root); }
            catch (Exception e) when (e is ArgumentException or NotSupportedException or PathTooLongException) { continue; }
            foreach (string folder in DataFolders)
                if (IsUnder(full, Path.Combine(rootFull, folder))) return (full, rootFull);
        }
        return null;
    }

    // ---- N229: the shipped-content manifest -------------------------------------------------------------------------

    /// <summary>N229: the manifest's file name, directly in each data root (<c>data/bundled.sha256</c>).</summary>
    public const string ManifestFileName = "bundled.sha256";

    /// <summary>
    /// N229: the content hash the manifest records for a file: SHA-256, as 64 lower-case hex digits, of the file's bytes
    /// with every CR LF pair read as a single LF (a git checkout on Windows writes the shipped text files with CR LF, one
    /// on Linux with LF; no other byte is changed). The generator (<c>tools/gen_bundled_manifest.py</c>) applies exactly
    /// this rule. A file that cannot be read throws, as reading it would.
    /// </summary>
    public static string ContentHash(string path)
    {
        byte[] bytes = File.ReadAllBytes(path);
        using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        int start = 0;
        for (int i = 0; i < bytes.Length; i++)
        {
            if (bytes[i] == (byte)'\r' && i + 1 < bytes.Length && bytes[i + 1] == (byte)'\n')
            {
                sha.AppendData(bytes, start, i - start);   // everything before the CR; the LF starts the next run
                start = i + 1;
            }
        }
        sha.AppendData(bytes, start, bytes.Length - start);
        return Convert.ToHexString(sha.GetHashAndReset()).ToLowerInvariant();
    }

    /// <summary>
    /// N229: parse a manifest's lines (the <c>sha256sum</c> text form): one <c>&lt;64 hex digits&gt;  &lt;path&gt;</c> per
    /// line, two spaces between, the path relative to the data root with <c>/</c> separators; blank lines are skipped.
    /// Returns null when any line is malformed or a path is listed twice (a manifest that cannot be trusted verifies
    /// nothing). Paths are compared with the platform's file-name rule (case-insensitive on Windows and macOS).
    /// </summary>
    public static IReadOnlyDictionary<string, string>? ParseManifest(IEnumerable<string> lines)
    {
        ArgumentNullException.ThrowIfNull(lines);
        var map = new Dictionary<string, string>(PathComparer);
        foreach (string raw in lines)
        {
            string line = raw.TrimEnd('\r', '\n');
            if (line.Trim().Length == 0) continue;
            if (line.Length < 67 || line[64] != ' ' || line[65] != ' ') return null;
            string hex = line[..64];
            if (!hex.All(c => c is >= '0' and <= '9' or >= 'a' and <= 'f')) return null;
            string rel = line[66..];
            if (rel.Length == 0 || rel.Contains('\\') || rel.StartsWith('/') || rel.Split('/').Any(s => s is "" or "." or "..")) return null;
            if (!map.TryAdd(rel, hex)) return null;
        }
        return map;
    }

    // The manifest of each data root, read once (null: absent or not trusted, so nothing under that root is bundled).
    private static readonly ConcurrentDictionary<string, IReadOnlyDictionary<string, string>?> Manifests = new(StringComparer.Ordinal);

    // Content hashes by file, keyed by its full path, size and last write time (a changed file is hashed again).
    private static readonly ConcurrentDictionary<(string Path, long Length, long Ticks), string> HashCache = new();

    // The manifest compiled into this assembly (null if the build carries none). It, not the file beside the data, is the
    // authority for the install's own data roots: the file sits in the very folder it protects and is unsigned, so anyone
    // able to drop a large network there could append its hash and have it treated as bundled (no bus limit).
    private static readonly IReadOnlyDictionary<string, string>? EmbeddedManifest = ReadEmbeddedManifest();

    private static IReadOnlyDictionary<string, string>? ReadEmbeddedManifest()
    {
        using Stream? s = typeof(BundledNetworks).Assembly.GetManifestResourceStream("GridSim.Core.bundled.sha256");
        if (s is null) return null;
        using var reader = new StreamReader(s);
        var lines = new List<string>();
        while (reader.ReadLine() is string line) lines.Add(line);
        return ParseManifest(lines);
    }

    private static IReadOnlyDictionary<string, string>? ManifestFor(string rootFull) => Manifests.GetOrAdd(rootFull, r =>
    {
        // An install data root: the embedded manifest only (a tampered or extended file beside the data is ignored).
        if (EmbeddedManifest is not null && DataRoots.Any(d => SamePath(d, r)))
            return EmbeddedManifest;
        string file = Path.Combine(r, ManifestFileName);
        try { return File.Exists(file) ? ParseManifest(File.ReadAllLines(file)) : null; }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException) { return null; }
    });

    private static string CachedHash(string fullPath)
    {
        var info = new FileInfo(fullPath);
        return HashCache.GetOrAdd((fullPath, info.Length, info.LastWriteTimeUtc.Ticks), k => ContentHash(k.Path));
    }

    // N229: true when 'full' (inside root 'rootFull') is a file the manifest lists with a matching hash, or a folder that
    // holds at least one file and only listed files with matching hashes. Any read failure: not shipped (licence applies).
    private static bool ContentIsShipped(string full, string rootFull)
    {
        IReadOnlyDictionary<string, string>? manifest = ManifestFor(rootFull);
        if (manifest is null) return false;
        try
        {
            if (File.Exists(full)) return Listed(full);
            if (!Directory.Exists(full)) return false;
            bool any = false;
            foreach (string f in Directory.EnumerateFiles(full, "*", SearchOption.AllDirectories))
            {
                if (!Listed(f)) return false;
                any = true;
            }
            return any;
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException) { return false; }

        bool Listed(string file)
        {
            string rel = Canonical(Path.GetRelativePath(rootFull, Path.GetFullPath(file)));
            return manifest.TryGetValue(rel, out string? want) && string.Equals(want, CachedHash(Path.GetFullPath(file)), StringComparison.Ordinal);
        }
    }

    private static StringComparer PathComparer =>
        OperatingSystem.IsWindows() || OperatingSystem.IsMacOS() ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;

    // Case rule for path comparison: the file systems GridSim ships on are case-insensitive on Windows and (by default)
    // macOS, case-sensitive on Linux.
    private static StringComparison PathComparison =>
        OperatingSystem.IsWindows() || OperatingSystem.IsMacOS() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;

    // Both paths in one separator form, without a trailing separator.
    private static string Canonical(string fullPath) => fullPath.Replace('\\', '/').TrimEnd('/');

    private static bool SamePath(string a, string b) =>
        string.Equals(Canonical(Path.GetFullPath(a)), Canonical(Path.GetFullPath(b)), PathComparison);

    // True when 'fullPath' is 'folder' itself or lies inside it, on whole segments (folder "data/uk" does not contain
    // "data/ukx"). Both arguments are full paths.
    private static bool IsUnder(string fullPath, string folder)
    {
        string p = Canonical(fullPath);
        string f = Canonical(Path.GetFullPath(folder));
        if (f.Length == 0) return false;
        return string.Equals(p, f, PathComparison)
            || (p.Length > f.Length && p.StartsWith(f, PathComparison) && p[f.Length] == '/');
    }
}
